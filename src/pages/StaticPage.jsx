const StaticPage = () => {
  // Read route from hash (e.g. "#/privacy-policy" -> "/privacy-policy")
  const hash = window.location.hash || '';
  const path = hash.startsWith('#') ? hash.slice(1) : '/';
  const data = pageData[path] || {
    title: 'Page Not Found',
    content: 'जिस पेज को आप ढूंढ रहे हैं वह मौजूद नहीं है या हटा दिया गया है।'
  };

  return (
    <div className="static-page-container">
      <div className="static-page-content">
        <h1 className="static-page-title">{data.title}</h1>
        <div className="static-page-body">
          {data.content.split('\n').map((paragraph, index) => (
            <p key={index}>{paragraph}</p>
          ))}
        </div>
        <button className="static-page-back-btn" onClick={() => window.location.hash = '#/'}>
          ← वापस होमपेज पर जाएं
        </button>
      </div>
    </div>
  );
};

